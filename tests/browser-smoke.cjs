const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const playwright = require('playwright');
const output = path.resolve('work/screenshots');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const options = { headless: true };
  const edge = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
  if (fs.existsSync(edge)) options.executablePath = edge;
  const browser = await playwright.chromium.launch(options);
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(process.env.MVP_URL || 'http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
    assert.match(await page.title(), /Wedding Wardrobe/);
    assert.equal(await page.locator('.dress-card').count(), 8, 'eight real illustrated looks');
    await page.locator('[data-filter="evening"]').click();
    assert.equal(await page.locator('.dress-card').count(), 3, 'evening filter');
    await page.locator('[data-filter="all"]').click();
    await page.locator('#dress-search').fill('Rosalie');
    assert.equal(await page.locator('.dress-card').count(), 1, 'search narrows looks');
    await page.locator('#dress-search').fill('no-such-look');
    assert.equal(await page.locator('.dress-card').count(), 0);
    assert.equal(await page.locator('#empty-catalog').isVisible(), true);
    await page.locator('#clear-filters').click();
    await page.locator('.dress-card[data-id="d01"] .save-look').click();
    assert.equal(await page.locator('#saved-count').innerText(), '1');
    await page.locator('.dress-card[data-id="d01"] .dress-open').click();
    assert.equal(await page.locator('#look-dialog').isVisible(), true);
    await page.locator('#reserve-look-button').click();
    assert.equal(await page.locator('#size-error').isVisible(), true, 'size is required');
    await page.locator('#size-options button[data-size="S"]').click();
    await page.locator('#reserve-look-button').click();
    await page.locator('#confirm-reservation').click();
    assert.equal(await page.locator('#name-error').isVisible(), true);
    await page.locator('#guest-name').fill('Taylor Guest');
    await page.locator('#guest-email').fill('not-email');
    await page.locator('#confirm-reservation').click();
    assert.equal(await page.locator('#email-error').isVisible(), true);
    await page.locator('#guest-email').fill('taylor@example.com');
    await page.locator('#confirm-reservation').click();
    assert.equal(await page.locator('#confirmation-panel').isVisible(), true);
    await page.locator('#look-dialog .dialog-close').click();
    assert.match(await page.locator('.dress-card[data-id="d01"]').innerText(), /Reserved by you/);
    await page.reload({ waitUntil: 'networkidle' });
    assert.match(await page.locator('.dress-card[data-id="d01"]').innerText(), /Reserved by you/);
    await page.locator('#my-looks-button').click();
    await page.locator('[data-my-tab="reservations"]').click();
    await page.locator('[data-cancel-booking]').click();
    await page.locator('#confirm-cancel').click();
    await page.locator('#my-looks-dialog .dialog-close').click();
    assert.doesNotMatch(await page.locator('.dress-card[data-id="d01"]').innerText(), /Reserved by you/);
    await page.locator('#change-wedding').click();
    await page.locator('#wedding-code').fill('invalid');
    await page.locator('#join-wedding-button').click();
    assert.equal(await page.locator('#room-error').isVisible(), true);
    await page.locator('#wedding-code').fill('ON2027');
    await page.locator('#join-wedding-button').click();
    assert.match(await page.locator('#room-names').innerText(), /Olivia/);
    assert.equal(await page.locator('#saved-count').innerText(), '0', 'favorites scoped to room');
    await page.locator('#change-wedding').click();
    await page.locator('#wedding-code').fill('EJ2027');
    await page.locator('#join-wedding-button').click();
    assert.equal(await page.locator('#saved-count').innerText(), '1');
    await page.locator('.dress-card[data-id="d03"] .dress-open').click();
    assert.equal(await page.locator('#reserve-look-button').isDisabled(), true, 'seeded reserved look cannot be booked');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#look-dialog').isVisible(), false);
    await page.waitForTimeout(3500);
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    await page.screenshot({ path: path.join(output, 'hero-desktop.png') });
    const badImages = await page.locator('img').evaluateAll(images => images.filter(im => !im.complete || !im.naturalWidth).map(im => im.src));
    assert.deepEqual(badImages, [], 'all web-sourced images load');
    for (const width of [375, 768]) {
      await page.setViewportSize({ width, height: 900 });
      await page.waitForTimeout(100);
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
      assert.equal(overflow, false, `no overflow at ${width}px`);
      await page.screenshot({ path: path.join(output, `mobile-${width}.png`), fullPage: true });
    }
    await page.setViewportSize({ width: 375, height: 812 });
    await page.locator('.dress-card[data-id="d08"] .dress-open').click();
    await page.screenshot({ path: path.join(output, 'look-mobile.png') });
    await page.locator('#size-options button[data-size="M"]').click();
    await page.locator('#reserve-look-button').click();
    await page.locator('#guest-name').fill('Mobile Guest');
    await page.locator('#guest-email').fill('mobile@example.com');
    await page.locator('#confirm-reservation').click();
    assert.equal(await page.locator('#confirmation-panel').isVisible(), true, 'mobile checkout works');
    await page.locator('#view-reservation').click();
    assert.equal(await page.locator('[data-my-tab="reservations"]').getAttribute('aria-selected'), 'true');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('[data-receipt]').click();
    const download = await downloadPromise;
    assert.match(download.suggestedFilename(), /demo\.txt$/);
    await page.locator('#my-looks-dialog .dialog-close').click();
    assert.deepEqual(errors, [], 'no browser errors');
    console.log('PASS: catalog, filters, favorites, room isolation, validation, reservation persistence, cancellation, keyboard dialogs, images, and responsive layouts.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
